/**
 * Lists files in apps/web/public/demo-images/ into a generated manifest so the web app only
 * requests photos that exist; missing ones go straight to the fallback tile with no 404s.
 * Drop real scrap photos named like the seed expects (e.g. hms-1.jpg) and re-run `pnpm generate`.
 */
import { existsSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const dir = resolve(root, 'apps/web/public/demo-images');

export function buildManifest(files: string[]): string {
  const media = files.filter((f) => /\.(jpe?g|png|webp|avif|mp4|webm)$/i.test(f)).sort();
  return (
    '// GENERATED by scripts/demoImages.ts — do not edit. Run `pnpm generate`.\n' +
    `export const DEMO_IMAGES: ReadonlySet<string> = new Set(${JSON.stringify(media.map((f) => `/demo-images/${f}`))});\n`
  );
}

function main() {
  const files = existsSync(dir) ? readdirSync(dir) : [];
  writeFileSync(resolve(root, 'apps/web/src/lib/demoImages.ts'), buildManifest(files));
  console.log(`demo images: ${files.length} file(s) in apps/web/public/demo-images`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
